def get_icon(name: str, color: str = "#74E6B0", size: int = 24) -> QIcon:
    """Returns a QIcon for the given icon name, stroke color, and size."""
    template = SVG_ICONS.get(name)
    if not template:
        template = SVG_ICONS["about"]
    
    svg_string = template.format(color=color)
    renderer = QSvgRenderer(QByteArray(svg_string.encode("utf-8")))
    pixmap = QPixmap(size, size)
    pixmap.fill(QColor(0, 0, 0, 0))
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()
    return QIcon(pixmap)


